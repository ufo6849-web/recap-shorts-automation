"""대본 생성 프롬프트 (한국어). 입력 topic.json -> 프롬프트 문자열. 출력 형식은 docs/02 3.1절 script.json."""
from __future__ import annotations

RULES = """\
[형식 규칙]
1. title_lines: 제목 2줄. 각 줄 14자 이내(공백 포함). 두 줄을 이어 읽으면 명사로 끝나는 한 덩어리가 되게 쓴다(아래 훅 꼴). 2줄째가 가장 궁금하게.
2. hook: 첫 내레이션. title_lines 두 줄을 그대로 이어 읽은 말이 기본이다(맨 위 제목·인트로 카드·첫 말이 모두 같은 글자).
   꼴: [현재/진짜/결국/의외로/최근 중 하나(없어도 됨)] + [~다는/~라는/~한 + 대상] + [근황/이유/진실/정체/비밀/결과/수준 같은 명사].
   앞머리 말(진짜/결국/의외로…)은 뜻이 맞을 때만 붙이고, 들으면 바로 무슨 이야기인지 그려지게 쓴다("의외로 한 가게에서 나왔다는 배달 답글 수준" ✗ 무엇이 의외인지 모름).
   12~20음절, 소리 내어 2.5초 안팎. 서술어로 끝내지 않는다("~올라왔어", "~했대", "~터졌다" 꼴 금지). "실베에", "오늘자 국야갤" 같은 출처 말은 넣지 않는다.
   (꼴 예: "의외로 불법이 아니라는 골목 주차 방법", "결국 밝혀졌다는 고양이가 상자를 좋아하는 이유", "18년 만에 바뀌었다는 동네 버스 번호")
3. sentences: hook 다음에 이어지는 본문 문장들. hook 을 sentences 에 다시 쓰지 말 것. 문장 하나는 보통 15~25음절.
4. 분량: hook + sentences + closing 의 전체 음절 수 약 204 (190~220). 한글 한 글자가 1음절, 숫자는 읽는 대로(980 = 구백팔십 4음절).
5. 말투: 친구에게 이야기해 주는 반말 구어체. 아래 [문장 흐름 규칙]을 지킨다.
6. closing: 마지막 한 줄은 내레이터의 반응(감탄·평가·물음). 구독·좋아요·알림 설정 요청은 절대 쓰지 말 것.

[문장 흐름 규칙 - 소리 내어 읽었을 때 자연스러운 대본 (대사가 어색하고 문장 흐름이 튀는 문제를 줄이기 위한 규칙)]
F1. 이야기 순서: 상황(무슨 일이 있었나) → 반전(알고 보니) → 구체적인 장면 2~3개 → 대비나 결말 → 반응. 앞 문장을 들어야 다음 문장이 이해되게 이어 쓴다.
F2. 문장 하나에 생각 하나. 사실을 쉼표로 줄줄이 붙이지 말고, 주어와 서술어가 분명한 완결된 말로 쓴다.
F3. 연결어를 문장 앞에 붙이지 말고 말 속에서 잇는다(받아쓰기 비교 측정).
    - 문장 첫머리 접속사는 대본 전체에 2번까지, 그중 "근데"는 1번까지(기준 1000어절당 1.2~5.2번, 우리 10.8~12.3번).
    - "심지어", "반면", "웃긴 건", "알고 보니", "덕분에" 같은 꾸밈 연결어는 모두 합쳐 1번까지. 잘 쓰지 않는데(1000어절당 0~1.3) 우리 대본은 많아서(심지어 8.6, 반면 4.9) AI 대본 티가 난다.
    - 대신 앞 말을 "~는데", "~더니", "~고" 로 받아 한 번 꺾어 잇는다(예: "10만 원이 더 나왔는데, 따지고 보면 이게 이득이야"). 꼭 접속사가 필요하면 "결국", "바로".
F4. 끝맺음은 친구에게 말하는 반말 하나로 맞춘다(반말 사이에 "~했다·~한다고 한다"가 끼어 뉴스처럼 튀는 문제가 있었다).
    - "~었어", "~거든", "~잖아", "~지", "~야", "~더라고"를 고루 섞는다. 해라체 평서("~했다", "~였다", "~이다", "~한다", "~한다고 한다")는 쓰지 않는다.
    - 전해 들은 꼴("~했대", "~래", "~더라", "~했다는데")은 2~3번까지. 모든 문장을 전해 들은 꼴로 끝내지 말고, 글 속 장면은 눈앞의 일처럼 말해도 된다("결혼 날까지 잡았대" → "결혼 날까지 잡은 상태였어").
    - 같은 끝맺음을 세 문장 연달아 쓰지 않는다. 물음("~일까?", "~뭘까?")은 1~2번.
F5. 압축하지 말고 풀어서 말한다. 나쁜 예 → 좋은 예:
    - "주말 선수는 평일 배송 일하고 2안타 쳤다고 해." → "야구는 주말에만 하는 직장인 선수인데, 평일엔 배송 일을 하고 그날 안타를 두 개나 쳤어."
    - "옆 회사 직원이라는 말까지 돌았고," → "관중 중에 '방금 안타 친 사람이 우리 회사 후배'라고 말한 사람이 있었다는 글도 올라왔어."
    - "선발 아홉 명 중 세 명은 같은 회사 직원이라더라고." → "선발로 나온 선수 아홉 명 가운데 세 명이 같은 회사 직원이었어."
F6. 소리 내어 읽었을 때 숨이 차지 않게 한 문장 15~30음절. 30음절이 넘거나 일이 두 가지면 두 문장으로 나눈다(인용 하나·사건 하나에 문장 하나). 명사를 줄줄이 쌓지 않는다("연봉 억대 프로 선수 소속 구단" 같은 꼴 금지).
F7. 줄임말·영문 약어(AG, KBO 등)는 말로 풀어 쓴다("아시안게임"). 듣고 바로 알기 어려운 전문어(야구 기록 용어 등)는 쉬운 말로.
F8. 마지막 줄(closing)은 앞 이야기를 받아치는 한 마디. 새로운 사실을 넣지 않고, 앞에서 말한 사실과 어긋나지 않는다(예: "배달은 접었대" 뒤에 "어떻게 아직 장사가 될까?" ✗).
F9. 우리 해석 한 문장 이상 (유튜브 쇼츠는 남의 글에 내레이션만 얹은 영상을 '재사용 콘텐츠'로 보고 도달을 줄인다). sentences 안에 글 내용을 다시 전하는 문장이 아니라 "우리 쪽 정리·맥락·비교·관점"인 문장을 1~2개 넣고 그 문장에 "take": true 를 적는다(나머지는 false).
    - 무엇을: 이 일이 왜 눈길을 끄는지, 사람들이 놓치기 쉬운 것, 글 속 두 쪽(글쓴이와 댓글, 앞 의견과 뒤 의견)의 비교, 한 줄 교훈 중 하나.
    - 글에 있는 말을 바꿔 쓰거나 줄여 읽은 요약은 해석이 아니다. 글의 댓글·원문 댓글에 이미 있는 반응을 옮긴 말도 해석이 아니다. 그 문장만 들어도 원문에 없는 생각이 하나 들어 있어야 한다.
    - 앞 문장에 이어 친구한테 말하듯 자연스러운 반말로 쓴다("~인 셈이지", "~라서 더 웃긴 거야", "결국 ~였던 거지"). "내 눈엔", "정리하면" 같은 틀 말로 시작하지 않는다. 사실처럼 단정하지 말고, 원문보다 부풀리지 말고("배달을 접었다" → "가게 문을 닫았다" ✗), 원문에 없는 숫자·이름·사건·통계를 만들지 말 것. 숫자·영문·고유명사 없이 쓴다(규칙 8).
    - 이 문장은 evidence 와 source_id 를 null 로 둔다. image_hint 는 이 생각이 가리키는 글·댓글 캡처를 쓴다.
    - 자리: 구체적인 장면 2~3개를 지난 뒤, closing 바로 앞 본문에 둔다(F1 의 "대비나 결말"). closing 은 F8 대로 반응 한 마디라서 해석 문장을 대신하지 못한다. 길이는 F6 대로 15~30음절, 전체 분량(규칙 4) 안에 넣는다.
F10. 글의 재미가 사람이 한 말(리뷰 답글·댓글·문자·대사)에 있으면, 가장 어이없는 말 2~4개를 작은따옴표로 원문 글자 그대로 옮겨 들려준다.
    - 뭉뚱그려 풀어 쓰지 말 것: "사장은 말만 많다며 받아쳤다" ✗ → "국물이 싱겁다는 리뷰엔 사장님이 '그럼 안 먹으면 되지' 한 마디만 달았어" ✓.
    - 따옴표 안은 원문 그대로(맞춤법이 틀려도 그대로), 한 번에 25자 이내. 욕설·비하·남을 깎아내리는 말이 든 것은 고르지 않는다.
    - 그 문장의 evidence 는 따옴표 말이 들어 있는 원문 구절.
F11. 말한 사람이 둘 이상이면(리뷰와 답글, 글쓴이와 댓글) 문장마다 누가 한 말인지 주어로 밝힌다.
    - "~했다는 글엔 자기도 먹고 싶다며 달았지" ✗(누가 무엇을 달았는지 없음) → "음식을 다 남겼다는 손님한테 사장님은 '저도 그 메뉴 좋아해요'라고 답했어" ✓.
    - 들은 사람이 앞 문장 없이도 상황을 알 수 있게, 무엇에 대한 말인지(어떤 리뷰·어떤 글)를 짧게 붙인다.

[사실 규칙 - 가장 중요]
7. 사실을 말하는 문장마다 evidence 에 "원문(source_text)에 글자 그대로 있는 구절"을 10~60자로 복사해서 적는다. 요약·바꿔 쓰기 금지. 한 글자도 바꾸지 말 것.
8. 원문에 없는 숫자·이름·장소·사건을 만들지 말 것. 숫자나 영문 약어, 고유명사가 들어간 문장은 반드시 evidence 가 있어야 한다.
9. 커뮤니티 글에서 온 내용은 글쓴이·댓글이 한 말이라는 게 드러나게 쓴다("~라는 글이 올라왔는데", "~했다는데", "댓글엔 ~"). 확인 안 된 말(댓글의 뒷소식 등)을 사실로 단정하지 말 것. 전해 들은 끝맺음 수는 F4 대로 2~3번이면 충분하다.
10. 반응·연결 문장(사실 주장이 없는 문장)은 evidence 를 null 로 둔다. 그런 문장에는 숫자·고유명사를 넣지 말 것.
11. 실존 인물 비하, 확인되지 않은 사생활·의혹, 욕설, 혐오 표현 금지. 닉네임·아이디·IP 는 쓰지 말 것.

[장면 규칙]
12. 문장마다 image_hint: 그 문장이 나오는 동안 화면에 보여 줄 장면. 화면의 주인공은 실제 글·첨부 그림·댓글 캡처이고, AI 장면은 보조 설명이다.
   언제나 "AI 장면: (그 문장이 말한 사건·대상을 문자 그대로, 한국 이야기면 한국 장소로)"를 먼저 적고, 그 문장의 근거나 반응이 자료에 보이면 반드시 " / 캡처: (어느 부분인지 콕 집어서)"를 덧붙인다.
   분위기용 소품(노을, 화분, 손에 든 휴대폰, 빈 화면, 말풍선)으로 때우지 말 것. 감정이 핵심인 문장은 "표정이 보이는 보통 사람(지어낸 인물)의 반응"을 써도 된다.
   캡처는 줄·댓글 하나 단위로 적는다(그림 전체 X). 근거가 두 군데면 " / 캡처: …"를 두 번 적어도 된다.
   (예: "AI 장면: 카페 계산대 위에 놓인 긴 영수증 / 캡처: 영수증의 '합계' 줄", "AI 장면: 야구장 전광판의 빈 점수판 / 캡처: 댓글 '이게 진짜 실화냐'")
13. 실존 인물(글쓴이·기사 속 사람·연예인·선수·정치인)이 화면에 나와야 하는 장면은 image_hint 에 "실제 사진 필요(사용자/라이선스)"라고 적는다. 실존 인물이나 그 대역처럼 보이는 얼굴을 AI 로 만들라고 쓰지 말 것. 인물이 꼭 필요하지 않으면 사물·장소·자막 카드로 대신한다.
14. emphasis: 자막에서 색을 줄 낱말 하나(문장에 그대로 들어 있는 낱말, 없으면 null). source_id: 커뮤니티 글이면 "post", 뉴스 사실이면 facts 의 id, 반응·연결 문장은 null.
"""

SCHEMA = """\
{
  "title_lines": ["1줄", "2줄"],
  "hook": "훅 문장",
  "sentences": [
    {"text": "본문 문장", "evidence": "원문에 그대로 있는 구절 또는 null", "source_id": "post 또는 null",
     "emphasis": "낱말 또는 null", "image_hint": "장면 설명", "take": true 또는 false (F9 우리 해석 문장만 true)}
  ],
  "closing": "끝 한 줄(반응)",
  "flags": []
}"""


def build_prompt(topic: dict) -> str:
    kind = topic.get("source_kind", "user")
    kind_note = {
        "community": "출처는 인터넷 커뮤니티 글이다. 글 내용은 전해 들은 말로 쓴다. 훅에는 출처 말을 넣지 않는다.",
        "news": "출처는 뉴스 제목·요약이다. 보도된 내용만 쓰고 추측을 덧붙이지 말 것.",
        "user": "출처는 사용자가 준 글이다. 글에 있는 내용만 쓸 것.",
    }.get(kind, "")
    parts = [
        "너는 한국어 유튜브 쇼츠(35초 안팎, 이미지 슬라이드 + 내레이션) 대본 작가다.",
        "아래 주제와 원문만으로 대본 한 편을 쓴다.",
        "",
        f"[주제] {topic.get('topic', '')}",
        f"[출처 종류] {kind} - {kind_note}",
    ]
    if topic.get("source_url"):
        parts.append(f"[출처 주소] {topic['source_url']}")
    if topic.get("tone_end"):
        parts.append(f"[끝 한 줄 분위기] {topic['tone_end']}")
    parts += ["", "[원문 source_text - evidence 는 반드시 여기서 그대로 복사]", "<<<",
              (topic.get("source_text") or "").strip(), ">>>"]
    facts = topic.get("facts") or []
    false_claims = topic.get("false_claims") or []
    unverified = topic.get("unverified_claims") or []
    if facts:
        parts += ["", "[확인된 사실 facts - evidence 는 이 목록의 evidence 또는 위 원문에서]"]
        for f in facts:
            parts.append(f"- ({f.get('id')}) {f.get('text')} / evidence: {f.get('evidence')}")
    if false_claims:
        parts += ["", "[사실 아님 주장 false_claims - 뉴스로 확인해 사실이 아니다. 사실처럼 말하지 않는다]"]
        for c in false_claims:
            parts.append(f"- ({c.get('id')}) {c.get('claim')}")
    if unverified:
        parts += ["", "[확인되지 않은 주장 unverified_claims - 보도로 확인되지 않았다. 이 주장의 수치·내용은 쓰지 않는다]"]
        for c in unverified:
            parts.append(f"- ({c.get('id')}) {c.get('claim')}")
    if facts or false_claims or unverified:
        parts += ["", "[사실 확인 규칙]",
                  "- 원문과 확인된 사실(facts)이 다르면 facts를 따른다.",
                  "- 사실 아님 주장(false_claims)은 사실처럼 말하지 않는다.",
                  "- 확인되지 않은 주장(unverified_claims)의 수치·주장은 쓰지 않는다."]
    parts += ["", RULES, "[출력 형식] 아래 JSON 객체 하나만 출력한다.", SCHEMA]
    return "\n".join(parts)
